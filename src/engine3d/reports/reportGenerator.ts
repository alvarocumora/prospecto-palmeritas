// Report Generator — Sprint 5
// Genera reportes JSON/HTML con secciones técnicas (ejecutivo, geología, QA/QC,
// recursos, targets, drill plan, economía, supuestos, NI 43-101 cautionary note).

import type { BlockModelOutput } from "@/engine3d/workers/blockModel.worker";
import type { QAQCResult } from "@/engine3d/qaqc/qaqc.worker";
import type { ParsedDrillholeBundle } from "@/engine3d/data/csvDrillholes";
import type { AIInterpretation } from "@/engine3d/ai/aiGeologist";
import type { DrillTarget, DrillTargetOutput } from "@/engine3d/ai/drillTarget.worker";

export type ReportEcon = {
  price: number;
  opex: number;
  capex: number;
  recovery: number;
  discount: number;
  years: number;
};

export type ReportInput = {
  projectId: string;
  projectName?: string;
  generatedAt: string;
  ai: AIInterpretation | null;
  blockModel: BlockModelOutput | null;
  qaqc: QAQCResult | null;
  bundle: ParsedDrillholeBundle | null;
  targets: DrillTargetOutput | null;
  scenarioTargets: DrillTarget[];
  econ: ReportEcon;
  campaignCost: number;
};

export type ReportSection = {
  id: string;
  title: string;
  body: string[];
};

export type ReportJson = {
  projectId: string;
  projectName?: string;
  generatedAt: string;
  sections: ReportSection[];
  raw: {
    ai: AIInterpretation | null;
    resourceSummary: BlockModelOutput["stats"] | null;
    qaqcSummary: QAQCResult["summary"] | null;
    targetStats: DrillTargetOutput["stats"] | null;
    scenarioTargetIds: string[];
    econ: ReportEcon;
    campaignCost: number;
  };
};

const CAUTIONARY_NOTE =
  "This report is preliminary and was generated by an automated mining intelligence engine. " +
  "It is NOT a NI 43-101 compliant technical report. A Qualified Person (QP) must independently " +
  "validate all data, QA/QC procedures, estimation methodology, and economic assumptions before " +
  "any public disclosure or investment decision.";

export function buildReport(input: ReportInput): ReportJson {
  const sections: ReportSection[] = [];

  // 1. Executive summary
  sections.push({
    id: "executive",
    title: "Executive Summary",
    body: input.ai
      ? [
          input.ai.headline,
          ...input.ai.interpretation,
          `Upside assessment: ${input.ai.upside.toUpperCase()}. Uncertainty: ${input.ai.uncertainty.toUpperCase()}.`,
        ]
      : ["No AI interpretation available for this run."],
  });

  // 2. Geological setting
  sections.push({
    id: "geology",
    title: "Geological Setting & Anomaly Footprint",
    body: input.ai
      ? [
          `Total anomalies: ${input.ai.stats.anomalies} (${input.ai.stats.geophysics} geophysical / ${input.ai.stats.satellite} satellite).`,
          input.ai.stats.bboxAreaKm2
            ? `Anomalous footprint: ~${input.ai.stats.bboxAreaKm2.toFixed(2)} km².`
            : "Footprint area: not determined.",
          input.ai.stats.avgSpacingM
            ? `Average drillhole spacing: ${input.ai.stats.avgSpacingM.toFixed(0)} m.`
            : "Drillhole spacing: insufficient data.",
        ]
      : ["No geological data available."],
  });

  // 3. Data sources
  sections.push({
    id: "data",
    title: "Data Sources",
    body: [
      `Project ID: ${input.projectId}`,
      input.bundle
        ? `Imported drillhole bundle: ${input.bundle.collars.length} collars, ${input.bundle.surveys.length} surveys, ${input.bundle.assays.length} assays, ${input.bundle.lithology.length} lithology intervals.`
        : "No external drillhole CSV bundle imported (using project database).",
      input.bundle && input.bundle.errors.length > 0
        ? `Import errors: ${input.bundle.errors.length} rows rejected.`
        : "No import errors reported.",
    ],
  });

  // 4. QA/QC
  sections.push({
    id: "qaqc",
    title: "QA/QC Results",
    body: input.qaqc
      ? [
          `Critical issues: ${input.qaqc.summary.critical}.`,
          `Warnings: ${input.qaqc.summary.warning}.`,
          `Info: ${input.qaqc.summary.info}.`,
          `Total holes validated: ${input.qaqc.summary.totalHoles}, total assays: ${input.qaqc.summary.totalAssays}.`,
          `QA/QC hash: ${input.qaqc.summary.hash}.`,
        ]
      : ["QA/QC validation not executed in this run."],
  });

  // 5. Resource model
  sections.push({
    id: "resource",
    title: "Resource Model",
    body: input.blockModel
      ? [
          `Block model: ${input.blockModel.count.toLocaleString()} blocks (block size ${input.blockModel.blockSize.x}×${input.blockModel.blockSize.y}×${input.blockModel.blockSize.z} m).`,
          `Mean grade: ${input.blockModel.stats.gradeMean.toFixed(3)} (range ${input.blockModel.stats.gradeMin.toFixed(2)}–${input.blockModel.stats.gradeMax.toFixed(2)}).`,
          `Total tonnage: ${(input.blockModel.stats.tonnesTotal / 1_000_000).toFixed(2)} Mt @ density ${input.blockModel.density} t/m³.`,
          `Contained metal: ${input.blockModel.stats.metalTotal.toLocaleString(undefined, { maximumFractionDigits: 0 })} (${input.blockModel.commodity}).`,
          `Classification — Measured: ${input.blockModel.stats.measured}, Indicated: ${input.blockModel.stats.indicated}, Inferred: ${input.blockModel.stats.inferred}.`,
        ]
      : ["No block model active in this run."],
  });

  // 6. Exploration targets
  sections.push({
    id: "targets",
    title: "Exploration Targets",
    body: input.targets
      ? [
          `Total proposed targets: ${input.targets.stats.selected} (from ${input.targets.stats.candidates} candidates).`,
          `Priority A: ${input.targets.stats.aPriority}, B: ${input.targets.stats.bPriority}, C: ${input.targets.stats.cPriority}.`,
          `Estimated total meters: ${input.targets.stats.totalMeters.toFixed(0)} m.`,
          `Estimated total cost: $${input.targets.stats.totalCost.toLocaleString(undefined, { maximumFractionDigits: 0 })}.`,
        ]
      : ["No drill targets generated in this run."],
  });

  // 7. Drill plan (scenario)
  sections.push({
    id: "drillplan",
    title: "Drill Plan (Selected Scenario)",
    body:
      input.scenarioTargets.length > 0
        ? input.scenarioTargets.map(
            (t) =>
              `${t.targetId} · ${t.priority} · ${t.depth.toFixed(0)} m · az ${t.azimuth.toFixed(0)}°/dip ${t.dip.toFixed(0)}° · cost $${(t.estimatedCost / 1000).toFixed(0)}k · conf ${(t.confidence * 100).toFixed(0)}%`,
          )
        : ["No targets added to scenario."],
  });

  // 8. Economics
  sections.push({
    id: "economics",
    title: "Economic Assumptions & Campaign Cost",
    body: [
      `Metal price: $${input.econ.price}/unit · Recovery: ${input.econ.recovery}%.`,
      `OPEX: $${input.econ.opex}/t · CAPEX: $${(input.econ.capex / 1_000_000).toFixed(1)}M.`,
      `Discount rate: ${(input.econ.discount * 100).toFixed(1)}% · Mine life: ${input.econ.years} y.`,
      `Estimated drill campaign cost (scenario): $${input.campaignCost.toLocaleString(undefined, { maximumFractionDigits: 0 })}.`,
    ],
  });

  // 9. Assumptions & limitations
  sections.push({
    id: "assumptions",
    title: "Assumptions & Limitations",
    body: [
      "Block grade estimated via Inverse Distance Weighting (IDW) over anomaly intensity proxies.",
      "Classification radii are configurable; reported categories are indicative only.",
      "Economic projections use flat metal price and constant OPEX/CAPEX over the life-of-mine.",
      "Drill target ranking penalises QA/QC issues but does not replace expert geological judgement.",
      "AI Geologist outputs are deterministic heuristics over the data shown in the active session.",
    ],
  });

  // 10. Cautionary note
  sections.push({
    id: "cautionary",
    title: "NI 43-101 Cautionary Statement",
    body: [CAUTIONARY_NOTE],
  });

  return {
    projectId: input.projectId,
    projectName: input.projectName,
    generatedAt: input.generatedAt,
    sections,
    raw: {
      ai: input.ai,
      resourceSummary: input.blockModel?.stats ?? null,
      qaqcSummary: input.qaqc?.summary ?? null,
      targetStats: input.targets?.stats ?? null,
      scenarioTargetIds: input.scenarioTargets.map((t) => t.targetId),
      econ: input.econ,
      campaignCost: input.campaignCost,
    },
  };
}

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function renderReportHtml(report: ReportJson): string {
  const sectionsHtml = report.sections
    .map(
      (s) => `
    <section id="${s.id}">
      <h2>${escapeHtml(s.title)}</h2>
      <ul>${s.body.map((b) => `<li>${escapeHtml(b)}</li>`).join("")}</ul>
    </section>`,
    )
    .join("\n");
  const title = `Mining Intelligence Report · ${report.projectName ?? report.projectId}`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>${escapeHtml(title)}</title>
<style>
  body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; max-width: 880px; margin: 2rem auto; padding: 0 1.5rem; color: #1a1a1a; line-height: 1.55; }
  h1 { border-bottom: 2px solid #c9a84c; padding-bottom: .5rem; }
  h2 { margin-top: 2rem; color: #064e3b; }
  ul { padding-left: 1.25rem; }
  .meta { color: #666; font-size: .85rem; margin-bottom: 1.5rem; }
  .cautionary { background: #fff8e1; border-left: 4px solid #c9a84c; padding: 1rem; margin-top: 2rem; font-size: .9rem; }
  nav { font-size: .85rem; margin-bottom: 2rem; }
  nav a { margin-right: 1rem; color: #0d7a5f; }
</style>
</head>
<body>
<h1>${escapeHtml(title)}</h1>
<div class="meta">Generated ${new Date(report.generatedAt).toLocaleString()} · Project ${escapeHtml(report.projectId)}</div>
<nav>${report.sections.map((s) => `<a href="#${s.id}">${escapeHtml(s.title)}</a>`).join(" · ")}</nav>
${sectionsHtml}
<div class="cautionary">${escapeHtml(CAUTIONARY_NOTE)}</div>
</body>
</html>`;
}

export function downloadString(filename: string, content: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function exportTargetsCsv(targets: DrillTarget[]): string {
  const header = "targetId,priority,score,confidence,depth,azimuth,dip,collar_x,collar_y,zone,cost_usd,rationale";
  const rows = targets.map((t) =>
    [
      t.targetId,
      t.priority,
      t.score.toFixed(3),
      t.confidence.toFixed(3),
      t.depth.toFixed(1),
      t.azimuth.toFixed(1),
      t.dip.toFixed(1),
      t.collar.x.toFixed(2),
      t.collar.y.toFixed(2),
      t.expectedZone,
      t.estimatedCost.toFixed(0),
      `"${t.rationale.join(" | ").replace(/"/g, "'")}"`,
    ].join(","),
  );
  return [header, ...rows].join("\n");
}

export function campaignCost(targets: DrillTarget[]): number {
  return targets.reduce((s, t) => s + t.estimatedCost, 0);
}
